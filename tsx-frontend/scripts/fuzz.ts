// npm run fuzz -- --seeds N --start S [--no-reduce]
// Runs the differential fuzzer over seeds S..S+N-1 and writes .out/fuzz/run-S-N/: summary.json, summary.md, and for each
// divergence or generator bug a directory with the generated TSX/RX, the script, every leg's trace and, for a
// divergence, the reduced case.
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { emitRx, emitTsx, generate, type Case, type Handler, type Node, type Prog } from "../tsx/fuzz/gen.ts";
import { reduce, runCase } from "../tsx/fuzz/run.ts";

const arg = (name: string, dflt: number) => { const i = process.argv.indexOf(name); return i < 0 ? dflt : Number(process.argv[i + 1]); };
const seeds = arg("--seeds", 100), start = arg("--start", 0), reducing = !process.argv.includes("--no-reduce");
const out = fileURLToPath(new URL("../.out/fuzz/run-" + start + "-" + seeds + "/", import.meta.url));
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

const features = (p: Prog) => {
  const walk = (ns: Node[]): string[] => ns.flatMap(n => [n.k, ...(n.k === "show" ? walk(n.then).concat(walk(n.fallback)) : [])]);
  const kinds = new Set(walk(p.view));
  return [
    "signals", ...(p.memos.length ? ["memos"] : []), ...(p.store ? ["store"] : []), ...(p.action ? ["action"] : []),
    ...(kinds.has("show") ? ["Show"] : []), ...(kinds.has("rows") ? ["For"] : []), ...(kinds.has("child") ? ["child"] : []),
  ];
};
const tally: Record<string, number> = {}, covered: Record<string, number> = {};
const findings: { seed: number; status: string; classes?: string[]; where?: string; message?: string; reduced?: string }[] = [];
for (let seed = start; seed < start + seeds; seed++) {
  const c = generate(seed);
  for (const f of features(c.prog)) covered[f] = (covered[f] ?? 0) + 1;
  const o = await runCase(c);
  const key = o.status === "divergent" ? "divergent: " + o.classes.join(" + ") : o.status === "generator-bug" ? "generator bug (" + o.where + ")" : "ok";
  tally[key] = (tally[key] ?? 0) + 1;
  if (o.status === "ok") continue;
  const dir = out + "seed-" + seed + "/";
  mkdirSync(dir, { recursive: true });
  writeFileSync(dir + "App.tsx", o.tsx); writeFileSync(dir + "App.rx", o.rx);
  writeFileSync(dir + "case.json", JSON.stringify(c, null, 1));
  if (o.status === "generator-bug") { findings.push({ seed, status: o.status, where: o.where, message: o.message }); writeFileSync(dir + "error.txt", o.message + "\n"); continue; }
  writeFileSync(dir + "traces.json", JSON.stringify(o.traces, null, 1));
  const finding: (typeof findings)[number] = { seed, status: o.status, classes: o.classes };
  if (reducing) {
    const { reduced, runs } = await reduce(c, o.classes);
    const r = await runCase(reduced);
    writeFileSync(dir + "reduced.json", JSON.stringify(reduced, null, 1));
    writeFileSync(dir + "reduced.tsx", emitTsx(reduced.prog)); writeFileSync(dir + "reduced.rx", emitRx(reduced.prog));
    if (r.status === "divergent") writeFileSync(dir + "reduced-traces.json", JSON.stringify(r.traces, null, 1));
    finding.reduced = "seed-" + seed + "/reduced.tsx (" + runs + " reduction runs, " + reduced.script.length + " steps)";
  }
  findings.push(finding);
  console.log("seed", seed, key);
}
const shape = (c: Case) => {
  const hs: Handler[] = [];
  const walk = (ns: Node[]) => ns.forEach(n => { if (n.k === "button" || n.k === "child") hs.push(n.h); if (n.k === "show") { walk(n.then); walk(n.fallback); } });
  walk(c.prog.view);
  if (hs.some(h => h.amount !== undefined && h.writes.length)) return "a handler writes, then calls the action";
  if (hs.some(h => h.amount === undefined)) return "plain writes beside a pending action";
  return "actions only, overlapping";
};
const legs = (t: Record<string, string[]>) => Object.entries(t).map(([k, v]) => "    " + k.padEnd(16) + JSON.stringify(v)).join("\n");
writeFileSync(out + "findings.md", [
  "# Fuzz findings: seeds " + start + ".." + (start + seeds - 1), "",
  "Generated by `npm run fuzz -- --seeds " + seeds + " --start " + start + "`; each case is reduced greedily. Traces are",
  "`marker|frame` per step (init, click, answer, skip = no pending flight for that amount, nobutton).", "",
  ...findings.filter(f => f.status === "divergent" && f.reduced).flatMap(f => {
    const dir = out + "seed-" + f.seed + "/";
    const reduced: Case = JSON.parse(readFileSync(dir + "reduced.json", "utf8"));
    const traces = JSON.parse(readFileSync(dir + "reduced-traces.json", "utf8"));
    return [
      "## Seed " + f.seed + ": " + f.classes!.join(" + "), "",
      "Shape: " + shape(reduced) + ". Script: `" + JSON.stringify(reduced.script) + "`", "",
      "```tsx", emitTsx(reduced.prog).trimEnd(), "```", "", "```rx", emitRx(reduced.prog).trimEnd(), "```", "",
      "```", legs(traces), "```", "",
    ];
  }),
].join("\n"));
const summary = { start, seeds, tally, covered, findings };
writeFileSync(out + "summary.json", JSON.stringify(summary, null, 1));
writeFileSync(out + "summary.md", [
  "# Fuzz run: seeds " + start + ".." + (start + seeds - 1), "",
  ...Object.entries(tally).map(([k, n]) => "- " + k + ": " + n), "",
  "Programs using each feature: " + Object.entries(covered).map(([k, n]) => k + " " + n).join(", "), "",
  ...findings.map(f => "- seed " + f.seed + ": " + (f.classes?.join(" + ") ?? f.where + ": " + f.message) + (f.reduced ? " → " + f.reduced : "")),
].join("\n") + "\n");
console.log(JSON.stringify({ tally, covered }, null, 1));
console.log("wrote " + out);
